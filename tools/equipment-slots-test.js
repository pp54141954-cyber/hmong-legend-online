'use strict';
const assert = require('node:assert/strict');
const { createSim } = require('../server/sim.js');
const { CFG } = require('../shared/world.js');
const sim = createSim({rand:()=>0.5});
const make = cls => ({id:1,personal:[],c:{cls,lv:1,job:1,st:{},sk:{},bag:[],eq:{},zone:'village',x:0,y:0},hp:100,maxHp:100});
const guardian=make('ผู้พิทักษ์');
guardian.c.bag=[{id:'sword_wood',n:1},{id:'shield_wood',n:1}];
assert.equal(CFG.items.shield_wood.slot,'offhand');
assert.equal(sim.inv(guardian,'equip',0),'ok');
assert.equal(guardian.c.eq.weapon,'sword_wood');
assert.equal(sim.inv(guardian,'equip',0),'ok');
assert.equal(guardian.c.eq.offhand,'shield_wood');
assert.equal(guardian.c.eq.weapon,'sword_wood');
assert.equal(sim.inv(guardian,'unequip','offhand'),'ok');
assert.equal(guardian.c.eq.offhand,null);
assert(guardian.c.bag.some(x=>x.id==='shield_wood'));
const archer=make('นักธนู');archer.c.bag=[{id:'shield_wood',n:1},{id:'sword_wood',n:1}];
assert.equal(sim.inv(archer,'equip',0),'wrong-class');
assert.equal(sim.inv(archer,'equip',1),'wrong-class');
assert.equal(archer.c.bag.length,2);
console.log('PASS: guardian mainhand/offhand equipment isolation');
